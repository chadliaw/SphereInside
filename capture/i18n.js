let lang = "zh";

function t(key, params = {}) {
  const text = TEXT[lang][key] ?? TEXT.zh[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in params ? params[name] : "{" + name + "}"));
}

// 設定元素的文字，並記住鍵值，切換語言時會跟著更新
function setText(el, key, params) {
  el.dataset.i18n = key;
  if (params) el.dataset.i18nParams = JSON.stringify(params);
  else delete el.dataset.i18nParams;
  el.textContent = t(key, params);
}

// 不需要翻譯的文字（例如錯誤訊息原文）
function setRawText(el, text) {
  delete el.dataset.i18n;
  delete el.dataset.i18nParams;
  el.textContent = text;
}

function applyLanguage() {
  document.documentElement.lang = lang === "zh" ? "zh-Hant" : "en";
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, el.dataset.i18nParams ? JSON.parse(el.dataset.i18nParams) : undefined);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

function chooseLanguage(value) {
  lang = TEXT[value] ? value : "en";
  try { localStorage.setItem("sphereinside.lang", lang); } catch (_) { /* 無法儲存時只影響這一次 */ }
  applyLanguage();
}

(() => {
  let saved = null;
  try { saved = localStorage.getItem("sphereinside.lang"); } catch (_) { /* 沒有儲存的設定 */ }
  lang = saved && TEXT[saved] ? saved : (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
})();
